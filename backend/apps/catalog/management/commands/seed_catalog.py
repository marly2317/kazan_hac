class Command(BaseCommand):
    help = "Заполнить каталог демонстрационными товарами (идемпотентно)."

    def handle(self, *args, **options) -> None:
        created = 0
        for sku, name, category, price, unit, description in PRODUCTS:
            _, was_created = Product.objects.update_or_create(
                sku=sku,
                defaults={
                    "name": name,
                    "category": category,
                    "price": Decimal(price),
                    "unit": unit,
                    "description": description,
                },
            )
            created += int(was_created)

        # The stored vectors are derived columns: without this the rows exist but match nothing.
        updated = container.product_repository().refresh_search_vectors()
        CatalogVocabulary.invalidate()

        self.stdout.write(
            self.style.SUCCESS(
                f"Каталог: добавлено {created}, всего {Product.objects.count()}, "
                f"поисковых векторов обновлено {updated}."
            )
        )
