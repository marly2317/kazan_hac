_BY_CODE: dict[str, Unit] = {unit.code: unit for unit in UNITS}

def normalize_unit_text(text: str) -> str:
    """Свести написание единицы к сравнимому виду: регистр, ё, верхние индексы, лишние точки."""
    folded = text.strip().casefold().replace("ё", "е")
    folded = folded.replace("²", "2").replace("³", "3").replace("×", "x")
    folded = re.sub(r"\s+", " ", folded)
    # «кв. м» → «кв.м», «об. / мин» → «об./мин»
    folded = re.sub(r"\s*([./])\s*", r"\1", folded)
    return folded.rstrip(".") if folded not in {".", ""} else folded


_BY_SYNONYM: dict[str, Unit] = {}
for _unit in UNITS:
    for _synonym in (*_unit.synonyms, _unit.name):
        _BY_SYNONYM.setdefault(normalize_unit_text(_synonym), _unit)


def by_code(code: str | None) -> Unit | None:
    """Единица по коду ОКЕИ (или псевдокоду)."""
    if not code:
        return None
    return _BY_CODE.get(code.strip())


def by_okei(code: str | None, name: str | None = None) -> Unit | None:
    """Единица значения КТРУ: по коду, а если код незнаком — по названию."""
    unit = by_code(code)
    if unit is None and name:
        unit = parse_unit(name.split("(")[0].split(";")[0])
    return unit


def parse_unit(text: str | None) -> Unit | None:
    """Распознать единицу, как её написал человек. ``None`` — единица неизвестна."""
    if not text:
        return None
    key = normalize_unit_text(text)
    if not key:
        return None
    if key in _BY_SYNONYM:
        return _BY_SYNONYM[key]
    # «мм.» и «мм,» — хвостовая пунктуация
    stripped = key.strip(".,;:)")
    return _BY_SYNONYM.get(stripped)


def known_unit_words() -> list[str]:
    """Все написания единиц — для регулярного выражения «число + единица»."""
    return sorted(_BY_SYNONYM, key=len, reverse=True)


def unit_in_name(characteristic_name: str) -> Unit | None:
    """Единица, вписанная в название характеристики: «…, м/мин», «… (Нм)», «…, градус».

    У части числовых характеристик КТРУ нет ОКЕИ, а единица стоит в хвосте названия.
    Без неё «Максимальный крутящий момент (Нм)» нельзя было бы сравнить с «40 Н·м».
    """
    match = re.search(r"\(([^()]{1,20})\)\s*$", characteristic_name)
    if match:
        unit = parse_unit(match.group(1))
        if unit:
            return unit
    if "," in characteristic_name:
        tail = characteristic_name.rsplit(",", 1)[1]
        unit = parse_unit(tail)
        if unit:
            return unit
    return None


def convert(value: float, source: Unit, target: Unit) -> float | None:
    """Значение ``value`` из ``source`` в ``target``; ``None``, если размерности разные."""
    if source.code == target.code:
        return value
    if source.dimension != target.dimension:
        return None
    return value * source.factor / target.factor


def same_dimension(left: Unit | None, right: Unit | None) -> bool:
    return left is not None and right is not None and left.dimension == right.dimension


