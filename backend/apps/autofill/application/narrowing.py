"""Сужение множества позиций — запросом к движку, а не перебором в Python.

Здесь живёт то же правило, что в `AnalyzeDescription._verdict`, выраженное условием запроса.
Правило такое: **позиция выбывает только при явном противоречии.**

    характеристика с таким именем есть, и ни одно её допустимое значение не принимает
    названное  →  выбывает
    характеристика с таким именем есть, и значение допустимо                →  остаётся,
                                                                               и это «за»
    характеристики с таким именем у позиции нет вовсе                       →  остаётся,
                                                                               но это не «за»

Третий случай — причина, по которой правило вообще нетривиально. Позиции КТРУ объявляют разные
характеристики: у «Куртки зимней из кожи» может не быть записи «Сезонность», а у «Обуви» —
есть. Считать это молчание несогласием значило бы выбросить верный ответ и оставить неверный.

## Зачем переносить это в движок

Не ради переноса. До него сужение работало по **пулу** из трёхсот позиций, отобранных по
наименованию, — и позиция, чьё наименование оказалось на 301-м месте, не могла быть
восстановлена никакими характеристиками, сколько бы их ни совпало. Условие в запросе снимает
это ограничение: фильтр применяется ко всему индексу, а не к заранее отобранной сотне.

Побочная выгода — счётчики. Задача требует показывать, как идёт сужение; `track_total_hits`
даёт точное «сколько осталось» на каждом шаге вместо длины списка, обрезанного пулом.

## Что осталось нашим

Проверка значения на допустимость **для отчёта об ошибке** — `_judge` в use case. Движок
отбирает кандидатов, но сказать «значение 400 см не входит в диапазон 60…250 см» должен тот,
кто знает `Decimal` и формулировки: у движка числа `double`, а объяснение на границе диапазона
обязано быть точным.

Чистые функции: словарь DSL на входе доменных объектов, ни Django, ни соединения.
"""

from __future__ import annotations

from decimal import Decimal, InvalidOperation

from apps.autofill.domain.entities import ExtractedCharacteristic

#: Путь вложенных документов со значениями — см. `ktru/infrastructure/search/indexes.py`.
VALUES = "values"

#: Префикс имени подзапроса «за эту позицию». Движок возвращает сработавшие имена в
#: `matched_queries`, и счётчик поддержки получается готовым, без второго прохода по ответу.
SUPPORT_PREFIX = "support:"


def within(codes: list[str]) -> dict:
    """Условие «только эти позиции».

    Сужение идёт внутри **разрешённого наименования**, а не по всему индексу, и это следствие
    порядка: наименование определяется первым, и позиция, которую описание не называет, не
    может стать ответом ни при каком совпадении характеристик — так решает
    `NAME_OVERLAP_FLOOR`. Искать её характеристиками значило бы искать среди того, что уже
    отвергнуто.

    Зато счётчики шагов начинают читаться буквально: «было 14 — стало 2» — это 14 позиций с
    таким наименованием, а не 14 случайных строк, попавших в пул по триграммам.
    """
    return {"terms": {"code": codes}}


def keeps(item: ExtractedCharacteristic) -> dict:
    """Условие «эта позиция не противоречит распознанной характеристике».

    Ставится в `filter`: оно не влияет на оценку, оно решает, остаётся позиция или нет.
    """
    return {
        "bool": {
            "should": [
                # Характеристики с таким именем нет — позиция молчит, и молчание не вина.
                {"bool": {"must_not": [_nested(_named(item.name))]}},
                # Либо есть, и значение допустимо.
                supports(item),
            ],
            "minimum_should_match": 1,
        }
    }


def supports(item: ExtractedCharacteristic, *, named: bool = False) -> dict:
    """Условие «позиция подтверждает распознанную характеристику».

    ``named=True`` помечает подзапрос именем, чтобы движок сообщил о срабатывании в
    `matched_queries`. Так считается `support` кандидата — без отдельного запроса и без
    повторного разбора значений на нашей стороне.
    """
    inner = {"bool": {"filter": [_named(item.name), _admits(item)]}}
    name = f"{SUPPORT_PREFIX}{item.name}" if named else None
    return _nested(inner, name=name)


def declares(name: str) -> dict:
    """Условие «у позиции есть характеристика с таким именем».

    Нужно не для сужения, а для подсказки «что добавить дальше»: спрашивать про
    характеристику, которой у кандидатов нет, бессмысленно.
    """
    return _nested(_named(name))


def _nested(query: dict, *, name: str | None = None) -> dict:
    body = {
        "path": VALUES,
        "query": query,
        # Оценка вложенных документов не нужна: совпадение одного допустимого значения — это
        # «да» или «нет», а не «насколько». `none` избавляет движок от их сложения.
        "score_mode": "none",
    }
    if name:
        body["_name"] = name
    return {"nested": body}


def _named(name: str) -> dict:
    """Сопоставление имени характеристики — точное, по неразобранному полю.

    Не `match` с анализатором: имя пришло **из самого справочника** (его распознал текстовый
    проход по допустимым значениям), поэтому совпадать оно обязано буква в букву. Нечёткое
    сравнение здесь добавило бы возможность спутать «Высота шкафа» с «Высота стеллажа» на
    ровном месте.
    """
    return {"term": {f"{VALUES}.characteristic.raw": name}}


def _admits(item: ExtractedCharacteristic) -> dict:
    """Условие «одно из допустимых значений принимает названное».

    Разделение на числовое и текстовое — по наличию единицы измерения, в точности как в
    `_verdict`: именно так use case и решает, чем считать распознанное значение.
    """
    if item.unit:
        return _admits_number(item)
    return _admits_text(item.value)


def _admits_text(value: str) -> dict:
    """Точное совпадение с допустимым текстом.

    Регистр приведён при индексации, а не здесь: значение записывается один раз, а читается
    на каждый запрос. «Похожего на допустимое» значения не бывает — «Мужской» либо разрешён,
    либо нет.
    """
    return {"term": {f"{VALUES}.text": value.casefold()}}


def _admits_number(item: ExtractedCharacteristic) -> dict:
    """Числовое значение против точных значений и диапазонов КТРУ.

    Единица измерения в условии **не участвует** — и это не упущение. Значение приходит сюда
    уже приведённым к единице характеристики (`in_characteristic_units` при распознавании), и
    `_verdict` сравнивает его со всеми значениями характеристики, не глядя на их единицы.
    Добавить здесь проверку единицы значило бы сузить строже, чем сужал перебор, то есть
    поменять поведение под видом переезда.
    """
    try:
        number = float(Decimal(item.value))
    except (InvalidOperation, ArithmeticError, ValueError):
        # Нечисловое значение при заполненной единице — распознать такое нельзя, и сужать по
        # нему нечем. Условие, которое принимает всё: позиция не выбывает из-за того, чего мы
        # не разобрали.
        return {"match_all": {}}

    return {
        "bool": {
            "should": [
                {
                    "bool": {
                        "filter": [
                            {"term": {f"{VALUES}.value_kind": "exact"}},
                            {"term": {f"{VALUES}.exact": number}},
                        ]
                    }
                },
                {
                    "bool": {
                        "filter": [
                            {"term": {f"{VALUES}.value_kind": "range"}},
                            _above_minimum(number),
                            _below_maximum(number),
                        ]
                    }
                },
            ],
            "minimum_should_match": 1,
        }
    }


def _above_minimum(number: float) -> dict:
    """Нижняя граница соблюдена: её нет, либо она нестрогая и ``min ≤ n``, либо строгая
    и ``min < n``.

    Строгость границы разворачивается в два условия, потому что она хранится в **документе**, а
    не в запросе: `greater` и `greaterOrEqual` в КТРУ различаются, и спутать их — значит
    принять значение, которое справочник отвергает. Одним `range` этого не выразить: оператор
    пришлось бы выбрать до того, как известно, какой границе он достанется.
    """
    return {
        "bool": {
            "should": [
                {"bool": {"must_not": [{"exists": {"field": f"{VALUES}.minimum"}}]}},
                {
                    "bool": {
                        "filter": [
                            {"term": {f"{VALUES}.min_inclusive": True}},
                            {"range": {f"{VALUES}.minimum": {"lte": number}}},
                        ]
                    }
                },
                {
                    "bool": {
                        "filter": [
                            {"term": {f"{VALUES}.min_inclusive": False}},
                            {"range": {f"{VALUES}.minimum": {"lt": number}}},
                        ]
                    }
                },
            ],
            "minimum_should_match": 1,
        }
    }


def _below_maximum(number: float) -> dict:
    """Верхняя граница соблюдена. Зеркально :func:`_above_minimum`."""
    return {
        "bool": {
            "should": [
                {"bool": {"must_not": [{"exists": {"field": f"{VALUES}.maximum"}}]}},
                {
                    "bool": {
                        "filter": [
                            {"term": {f"{VALUES}.max_inclusive": True}},
                            {"range": {f"{VALUES}.maximum": {"gte": number}}},
                        ]
                    }
                },
                {
                    "bool": {
                        "filter": [
                            {"term": {f"{VALUES}.max_inclusive": False}},
                            {"range": {f"{VALUES}.maximum": {"gt": number}}},
                        ]
                    }
                },
            ],
            "minimum_should_match": 1,
        }
    }
