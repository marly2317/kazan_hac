"""Как спрашивать у движка позиции по наименованию.

Запрос собирается из **части описания, называющей товар** (см.
`apps.autofill.domain.query.split`), а не из описания целиком. До разделения в поиск по
наименованиям уходили и «48», и «размер» — слова, которых в наименовании позиции КТРУ не
бывает; они не помогали найти куртку, а размывали оценку.

## Четыре взгляда на одно наименование

Ни один из них не достаточен, и каждый закрывает слепое пятно остальных:

| Поле | Что ловит | Что упускает |
| --- | --- | --- |
| `name` | словоформы, синонимы: «шлифовальная» → «Шлифмашина» | склейку без общей основы |
| `head` | то, чем товар **является** | ничего — но говорит слишком мало в одиночку |
| `name.trigram` | опечатку в середине, составное слово | даёт шум на коротком запросе |
| `vector` | смысловую близость без общих букв | всегда возвращает «похожее», даже на бессмыслицу |

`head` нужен отдельным полем из-за позиций вида «Бур для перфоратора»: слово «перфоратор» в
наименовании есть, но как указание на то, **для чего** товар, а не что он такое. Повышенный вес
первого слова разводит их раньше, чем это приходится делать нашим порогом.

## Почему RRF, а не взвешенная сумма

Лексика даёт BM25 — величину неограниченную и зависящую от длины запроса; kNN даёт косинус в
``[0, 2]``. Сложить их — отдельная задача с отдельными ошибками: коэффициент, подобранный на
одном наборе запросов, перестаёт работать на другом. RRF складывает **места**, а не оценки, и
этой задачи просто не ставит. Поэтому сложение отдано движку
(`score-ranker-processor`, см. `ktru/infrastructure/search/indexes.py`), а не написано здесь.

Следствие, важное для всего остального: итоговая оценка — это **место**, а не похожесть. Решать
по ней «нашлось или нет» нельзя в принципе, и решение о воздержании остаётся за
`apps.autofill.domain.matching`, которое считает совпадение по словам наименования.
"""

from __future__ import annotations

from apps.autofill.domain.query import SplitQuery

#: Вес поля с полным наименованием. Основной сигнал.
NAME_BOOST = 3.0

#: Вес первого слова наименования — того, чем товар является.
#:
#: Ниже, чем у наименования целиком: «Шкаф» отвечает на «шкаф офисный металлический» хуже, чем
#: «Шкаф для одежды металлический», и поднимать однословные позиции выше уточнённых нельзя.
HEAD_BOOST = 2.0

#: Вес триграммного поля. Самый низкий из лексических: на коротком запросе триграммы случайно
#: совпадают у неродственных русских слов, и в одиночку это поле ранжирует плохо. Его работа —
#: вернуть в отбор то, что остальные поля не видят вовсе.
TRIGRAM_BOOST = 1.0

#: Доля триграмм запроса, которая должна найтись в наименовании.
#:
#: Без этого порога поле работало бы как прежняя сумма сходств по всей таблице: у любых двух
#: русских слов есть общая триграмма, и «отвертка» находила бы «Кровать детская». 60% — то,
#: ниже чего совпадение перестаёт говорить о родстве слов.
TRIGRAM_MINIMUM = "60%"

#: Вес имён характеристик позиции.
#:
#: Самый низкий вообще, и это сознательно: описание «шкаф высота 2000» называет характеристику,
#: и позиция, у которой такая характеристика **есть**, вероятнее той, у которой её нет. Но это
#: слабый довод — характеристика «Высота» есть у половины мебели, — поэтому он сдвигает порядок
#: лишь при прочих равных.
ATTRIBUTE_BOOST = 0.3


def search_body(
    query: SplitQuery,
    vector: list[float] | None,
    *,
    limit: int,
    filters: list[dict] | None = None,
    supports: list[dict] | None = None,
    count_only: bool = False,
) -> dict:
    """Тело запроса к индексу позиций.

    ``filters`` — условия сужения по характеристикам (`application/narrowing.py`). Они
    вставляются **в каждый подзапрос**, а не поверх: `hybrid` не принимает фильтр на верхнем
    уровне, потому что отбор в каждой ветви идёт независимо и слияние мест происходит уже после
    него. Фильтр, применённый поверх слияния, отрезал бы хвост уже посчитанного списка — то
    есть выдал бы меньше позиций, чем прошло условие.

    ``count_only`` возвращает тело без документов: нужно только «сколько осталось» для шага
    сужения.
    """
    filters = filters or []
    lexical = _lexical(query, filters, supports or [])

    branches: list[dict] = [lexical]
    if vector is not None:
        branches.append(_knn(vector, limit, filters))

    body: dict = {
        # Точное число, а не оценка: шаг сужения показывает пользователю «было 14 — стало 2», и
        # приблизительное «больше 10 000» там было бы бессмысленно. Справочник категорий
        # хакатона мал, и точный подсчёт по нему ничего не стоит.
        "track_total_hits": True,
        "size": 0 if count_only else limit,
    }

    # Одна ветвь — `hybrid` не нужен: сливать нечего, а конвейер стоил бы лишней фазы.
    body["query"] = {"hybrid": {"queries": branches}} if len(branches) > 1 else branches[0]

    if not count_only:
        body["_source"] = {
            # `values` — самое объёмное в документе, и именно оно нужно: распознавание
            # характеристик работает по допустимым значениям кандидатов. Раньше за ними шёл
            # отдельный запрос в Postgres; теперь они приходят вместе с кандидатом.
            "includes": ["code", "name", "okpd2_code", "values"]
        }

    return body


def _lexical(query: SplitQuery, filters: list[dict], supports: list[dict]) -> dict:
    """Лексическая ветвь: четыре поля, один `bool`.

    `should` внутри одной ветви, а не четыре ветви `hybrid`: все четыре дают BM25, то есть
    величины одной природы, и складывать их весами здесь можно — именно этого нельзя делать с
    косинусом. RRF остаётся для того, что действительно несравнимо.
    """
    name = query.name.strip()
    should: list[dict] = [
        {"match": {"name": {"query": name, "boost": NAME_BOOST}}},
        {"match": {"head": {"query": name, "boost": HEAD_BOOST}}},
        {
            "match": {
                "name.trigram": {
                    "query": name,
                    "minimum_should_match": TRIGRAM_MINIMUM,
                    "boost": TRIGRAM_BOOST,
                }
            }
        },
    ]
    if query.attributes.strip():
        should.append(
            {
                "match": {
                    "characteristic_names": {
                        "query": query.attributes,
                        "boost": ATTRIBUTE_BOOST,
                    }
                }
            }
        )

    # Совпадение по наименованию — **обязательное** условие ветви, и поэтому оно в `must`, а
    # не в `should` рядом с остальным. Будь оно одним из `should` при
    # `minimum_should_match: 1`, условие выполнил бы и подзапрос поддержки: в пул попала бы
    # позиция, чьё наименование к описанию не имеет отношения, на одном лишь основании, что
    # среди её допустимых значений есть «Мужской». Таких позиций в справочнике сотни.
    body: dict = {"must": [{"bool": {"should": should, "minimum_should_match": 1}}]}

    if supports:
        # Подзапросы «за эту позицию» — именованные, и движок вернёт сработавшие имена в
        # `matched_queries`: счётчик поддержки получается готовым, без второго запроса и без
        # повторного разбора значений у нас. Вес нулевой и отбора они не меняют — порядок
        # определяют наименование и надбавки в `PositionCandidate.rank`, где этот баланс и
        # обоснован.
        body["should"] = [
            {"constant_score": {"filter": clause, "boost": 0.0}} for clause in supports
        ]

    if filters:
        body["filter"] = filters

    return {"bool": body}


def _knn(vector: list[float], limit: int, filters: list[dict]) -> dict:
    """Векторная ветвь.

    ``k`` равен запрошенному числу кандидатов: HNSW — приближённый поиск, и просить у него
    больше соседей, чем нужно, значит платить за обход графа, результат которого будет
    отброшен.

    Фильтр передаётся самому `knn`, а не оборачивает его: иначе граф вернул бы ближайших
    соседей **без учёта** условия, и после отсечения осталось бы произвольно мало позиций — или
    ни одной, хотя условию отвечают сотни.
    """
    body: dict = {"vector": vector, "k": limit}
    if filters:
        body["filter"] = {"bool": {"filter": filters}}
    return {"knn": {"vector": body}}
