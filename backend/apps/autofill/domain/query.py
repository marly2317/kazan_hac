"""Разделение описания на «что это за товар» и «какой он».

Описание товара — это две разные фразы, слитые в одну строку:

    куртка зимняя из кожи женская 48 размер
    └──── наименование ────────┘ └─ характеристики ─┘

Искать позицию КТРУ нужно **первой** из них. До этого разделения в поиск уходило описание
целиком, и слова «48» и «размер» участвовали в ранжировании **наименований позиций** — хотя в
наименовании позиции их не бывает и быть не может: это значение характеристики и имя
характеристики. Они не помогали найти куртку, они размывали оценку и тянули наверх позиции,
у которых в наименовании случайно оказались похожие триграммы.

Поэтому разделение — не оптимизация, а исправление ошибки в постановке запроса: наименование
ищется по наименованиям, характеристики сужают найденное. Второе без первого бессмысленно
(характеристики есть у всех позиций), первое без второго неполно (одно наименование не
доводит до единственного кода).

## Чем решается, к какой части относится слово

Текста для этого недостаточно. «Кожи» в «куртка зимняя из кожи» — часть **наименования
позиции** («Куртка зимняя из кожи» есть в справочнике ровно в таком виде), а «кожи» в
«перчатки из кожи» — значение характеристики «Материал». Одно и то же слово, разные роли, и
различает их не грамматика, а справочник.

Отсюда правило: **спрашиваем справочник**. Слово, которое встречается в наименованиях
позиций, относится к наименованию; слово, которое встречается только в именах характеристик и
допустимых значениях, — к характеристикам. Числа и единицы измерения — к характеристикам
всегда: в наименовании позиции КТРУ числа не несут смысла.

Незнакомое слово остаётся в наименовании, и это важнее, чем кажется. «Отвертки» в КТРУ нет
вовсе; выбросив неизвестное слово, мы получили бы пустой запрос «крестовая PH2», нашли бы по
нему что-нибудь похожее и ответили уверенно и неверно. Воздержание — сильнейшая сторона
решения, и оно держится на том, что слово, которого справочник не знает, доходит до поиска.

Чистые функции и один протокол; где взять словарь — забота `infrastructure`.
"""

from __future__ import annotations

import re
from dataclasses import dataclass
from enum import StrEnum
from typing import Protocol


class Role(StrEnum):
    """К какой части описания отнесено слово."""

    #: Называет товар — уходит в поиск по наименованиям позиций.
    NAME = "name"
    #: Описывает товар — сужает найденное по характеристикам.
    ATTRIBUTE = "attribute"


class Lexicon(Protocol):
    """Словарь справочника, разделённый по роли слова.

    Два вопроса, а не один: роль слова определяется тем, **где** оно в КТРУ встречается, и
    пересечение этих множеств (слово и в наименованиях, и в характеристиках) решается в пользу
    наименования — см. :func:`split`.
    """

    def names(self, word: str) -> bool:
        """Слово встречается в наименовании хотя бы одной позиции."""
        ...

    def describes(self, word: str) -> bool:
        """Слово встречается в имени характеристики или в названии единицы измерения.

        Допустимые значения сюда **не** входят: в них лежат названия товаров («Отвертки»,
        «Пластик»), то есть лексика наименования. Обоснование — в
        `apps.ktru.infrastructure.lexicon.KtruLexicon._collect_describes`.
        """
        ...

    def key(self, word: str) -> str:
        """Ключ, под которым слово лежит в этом словаре."""
        ...


#: Числа и слова по отдельности. Альтернатива, а не одно выражение: «2000мм» написано слитно
#: не реже, чем раздельно, и разделить его обязан токенизатор, а не пользователь.
_TOKEN = re.compile(r"\d+(?:[.,]\d+)?|[0-9a-zа-яё]+", re.IGNORECASE)

#: Короче этого слово не спрашивается у словаря: предлог или частица, которую любой словарь
#: «знает», и роль она не определяет ни в ту, ни в другую сторону. Такие слова остаются в
#: наименовании — там они безвредны, потому что анализатор движка их всё равно отбросит.
MIN_CLASSIFIED = 3

#: Длиннее этого слово на месте единицы измерения единицей уже не бывает.
#:
#: Единица — это «мм», «кг», «шт», «м3»; слово в десять букв на том же месте («молоток 350
#: попугаев») единицей не является, но и наименованием товара тоже: оно стоит при числе,
#: значит описывает, а не называет.
MAX_UNIT_LENGTH = 24


@dataclass(frozen=True)
class Decision:
    """Куда отнесено одно слово и почему.

    Причина хранится не для отладки. Задача требует показывать, как идёт сужение; разделение
    запроса — первый его шаг, и «слово „размер“ отнесено к характеристикам, потому что в
    наименованиях позиций оно не встречается» — это то, что отличает объяснимый подбор от
    угадывания.
    """

    word: str
    role: Role
    reason: str


@dataclass(frozen=True)
class SplitQuery:
    """Описание, разобранное на части."""

    #: Исходный текст целиком — то, что видит пользователь, и то, из чего извлекаются значения.
    full: str
    #: Часть, называющая товар. Именно она уходит в поиск по наименованиям.
    name: str
    #: Часть, описывающая товар: числа, единицы, имена характеристик, значения.
    attributes: str
    decisions: tuple[Decision, ...] = ()

    @property
    def is_split(self) -> bool:
        """Разделение что-то изменило — значит о нём стоит сообщить в интерфейсе."""
        return bool(self.attributes) and self.name != self.full


def split(text: str, lexicon: Lexicon) -> SplitQuery:
    """Разделить описание на наименование и характеристики.

    Правила применяются к каждому слову по порядку, и порядок — это и есть решение:

    1. **число** — к характеристикам всегда; в наименовании позиции КТРУ число не несёт
       смысла, а в сужении оно и есть значение;
    2. **слово на месте единицы измерения** (сразу за числом) — к характеристикам, но только
       если справочник не знает его как слово наименования: «2 стола» ставит «стола» на место
       единицы, и отнести его к характеристикам значило бы потерять сам товар;
    3. **слово из наименований позиций** — к наименованию. Раньше остальных правил: «зимняя»
       и «кожи» есть и в наименованиях позиций, и в допустимых значениях, и в поиске они
       нужны — «Куртка зимняя из кожи» так и называется;
    4. **слово из имён характеристик или допустимых значений** — к характеристикам: «размер»,
       «высота», «материал» в наименованиях позиций не встречаются;
    5. **всё остальное** — к наименованию. Незнакомое слово может быть товаром, которого в
       справочнике нет, и дойти до поиска оно обязано: иначе вместо честного «не нашлось»
       получится уверенный неверный код.

    Если к наименованию не отнеслось ничего — возвращается исходный текст целиком. Пустой
    запрос нашёл бы «ближайшее» к пустоте, то есть что угодно.
    """
    tokens = [(match.group(0), match.start(), match.end()) for match in _TOKEN.finditer(text)]

    decisions: list[Decision] = []
    previous_was_number = False
    previous_end = -1

    for word, start, end in tokens:
        folded = word.casefold()

        if folded[0].isdigit():
            decisions.append(Decision(word, Role.ATTRIBUTE, "значение"))
            previous_was_number, previous_end = True, end
            continue

        # «Сразу за числом» — это отсутствие других слов между ними, а не отсутствие пробела:
        # «2000 мм» и «2000мм» — одно и то же, а «2000 мм высота» ставит на место единицы «мм»
        # и только его.
        in_unit_slot = (
            previous_was_number
            and start - previous_end <= 1
            and len(folded) <= MAX_UNIT_LENGTH
        )
        previous_was_number, previous_end = False, end

        word_key = lexicon.key(folded)
        in_names = lexicon.names(word_key)

        # Место единицы проверяется **до** длины, и порядок здесь существенный. Единицы коротки
        # по природе — «мм», «кг», «шт», — и проверка длины, стоявшая раньше, объявляла их
        # «слишком короткими, чтобы решать» и оставляла в наименовании. В поиск по
        # наименованиям уходило «шкаф офисный мм металлический».
        if in_unit_slot and not in_names:
            decisions.append(Decision(word, Role.ATTRIBUTE, "стоит на месте единицы измерения"))
            continue

        if len(folded) < MIN_CLASSIFIED:
            decisions.append(Decision(word, Role.NAME, "слишком короткое, чтобы решать"))
            continue

        if in_names:
            decisions.append(Decision(word, Role.NAME, "встречается в наименованиях позиций"))
            continue

        if lexicon.describes(word_key):
            decisions.append(
                Decision(word, Role.ATTRIBUTE, "встречается только в характеристиках")
            )
            continue

        decisions.append(Decision(word, Role.NAME, "справочнику неизвестно"))

    name = " ".join(item.word for item in decisions if item.role is Role.NAME)
    attributes = " ".join(item.word for item in decisions if item.role is Role.ATTRIBUTE)

    if not name.strip():
        return SplitQuery(
            full=text, name=text, attributes=attributes, decisions=tuple(decisions)
        )

    return SplitQuery(full=text, name=name, attributes=attributes, decisions=tuple(decisions))
