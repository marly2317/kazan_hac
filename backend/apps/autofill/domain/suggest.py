"""Подсказки по мере набора — то, что браузер делает в адресной строке.

Зачем это здесь, а не «просто удобство»: главная беда пользователя — написать слово, которого
в КТРУ нет. «Отвертка» в справочнике отсутствует вовсе, и узнаёт об этом пользователь только
после того, как дописал описание до конца и получил «не нашлось». Подсказка показывает словарь
справочника **во время набора**, то есть уводит от тупика до того, как в него упрутся.

Поэтому подсказываются не произвольные русские слова, а ровно то, чем оперирует КТРУ:
наименования позиций, имена характеристик и допустимые значения.

Чистые типы и правила ранжирования; построение индекса и работа с базой — в `infrastructure`.
"""

from __future__ import annotations

from dataclasses import dataclass
from enum import StrEnum


class SuggestionKind(StrEnum):
    """Откуда взята подсказка. Решает и вес, и подпись в интерфейсе."""

    #: Слово из наименования позиции — ведёт прямо к коду, поэтому самое ценное.
    POSITION = "position"
    #: Имя характеристики: «высота», «материал».
    CHARACTERISTIC = "characteristic"
    #: Допустимое значение: «Металлический», «Зима».
    VALUE = "value"


#: Во сколько раз подсказка из наименования позиции важнее прочих.
#:
#: Цель набора — дойти до кода КТРУ, и слово, приближающее к позиции, полезнее слова,
#: уточняющего характеристику позиции, которая ещё не выбрана.
WEIGHTS: dict[SuggestionKind, int] = {
    SuggestionKind.POSITION: 100,
    SuggestionKind.CHARACTERISTIC: 20,
    SuggestionKind.VALUE: 10,
}


@dataclass(frozen=True)
class Suggestion:
    """Одно предложение продолжения."""

    #: Слово, которое подставится вместо набираемого.
    word: str
    kind: SuggestionKind
    #: Фраза справочника, откуда слово взято, — показывается серым как пояснение.
    #: «зимняя» само по себе ничего не говорит, «Куртка зимняя из кожи» говорит всё.
    source: str
    #: Насколько часто слово встречается в справочнике. Разрешает ничьи по весу.
    frequency: int
    #: Слово стоит **первым** в наименовании позиции, то есть называет сам товар.
    #:
    #: Без этого признака вес источника давал неверный порядок: наименования позиций
    #: описательны, и каждое прилагательное внутри них получало высший вес наравне с
    #: существительным. На префиксе «по» первым шло «пониженных» — из «Обувь специальная для
    #: защиты от пониженных температур», — а не «полупальто», хотя пользователь набирает
    #: название товара, а не хвост чужого наименования.
    is_head: bool = False

    @property
    def rank(self) -> tuple[int, int, int, int, str]:
        """Порядок показа: сначала названия товаров, затем вес источника, частота, длина.

        Короткие раньше длинных при прочих равных: «стол» вероятнее «столешница», когда
        набрано «сто», — пользователь чаще называет товар, чем его часть.
        """
        return (
            0 if self.is_head else 1,
            -WEIGHTS[self.kind],
            -self.frequency,
            len(self.word),
            self.word,
        )


#: Насколько слова могут разойтись в хвосте, оставаясь одним словом.
#:
#: Русский склоняет окончание: «металлический», «металлическим», «металлическая» — это одно
#: слово в списке подсказок, и показывать все четыре формы значит вытеснить ими настоящие
#: варианты. Два символа, не больше: при трёх «отверстия» и «отвертки» схлопнулись бы в одно,
#: а это разные вещи.
INFLECTION_TAIL = 2

#: Ниже этой длины общее начало ничего не значит.
MIN_SHARED = 5


def same_word(left: str, right: str) -> bool:
    """Формы одного слова: расходятся только в хвосте."""
    shorter, longer = sorted((left, right), key=len)
    shared = 0
    for one, other in zip(shorter, longer, strict=False):
        if one != other:
            break
        shared += 1
    return shared >= max(MIN_SHARED, len(shorter) - INFLECTION_TAIL)


def rank(suggestions: list[Suggestion], limit: int) -> list[Suggestion]:
    """Упорядочить и обрезать, оставив каждое слово один раз.

    «Один раз» в двух смыслах. Одно и то же слово приходит из многих фраз — «зимняя» есть и у
    куртки, и у обуви, — и повторы вытесняют другие варианты. И формы одного слова тоже
    считаются повтором: см. :func:`same_word`.

    Побеждает вариант, стоящий выше по ранжированию, потому что отсев идёт по уже
    отсортированному списку: это самая частая форма из самого весомого источника.
    """
    kept: list[Suggestion] = []
    for item in sorted(suggestions, key=lambda s: s.rank):
        if any(same_word(item.word, chosen.word) for chosen in kept):
            continue
        kept.append(item)
        if len(kept) >= limit:
            break
    return kept


def split_tail(text: str) -> tuple[str, str]:
    """Разделить набранное на «уже законченное» и «слово, которое набирают сейчас».

    Пробел в конце означает, что слово дописано и пользователь ждёт следующего — именно по
    этому признаку подсказка переключается с дополнения слова на предложение следующего.
    """
    if not text or text[-1].isspace():
        return text.strip(), ""
    parts = text.rsplit(maxsplit=1)
    if len(parts) == 1:
        return "", parts[0]
    return parts[0], parts[1]
