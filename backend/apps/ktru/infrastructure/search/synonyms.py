"""Народные названия товаров и их наименования в КТРУ.

Корзина `synonym` в замере (`manage.py bench_retrieval`) — единственная, которую не
закрывает ни морфология, ни триграммы: «болгарка» и «Шлифмашина» не имеют общих букв, и
никакое нечёткое сравнение их не свяжет. Связывает только знание о том, что это одна вещь.

Такое знание бывает двух видов, и здесь выбран дешёвый. «Болгарка → Шлифмашина» — это строка
в словаре, а не задача машинного обучения: она детерминирована, проверяема, объяснима в
интерфейсе и не требует ни модели, ни видеопамяти. На три категории хакатона таких строк
десятки, а не тысячи.

Применяет словарь сам движок — фильтром `synonym_graph` на этапе анализа, то есть один раз
при индексации и один раз при разборе запроса. Нам остаётся сам словарь; это и есть та часть,
которую нельзя передать движку, потому что она про предметную область, а не про поиск.

## Почему `=>`, а не `,`

Направленная замена, а не группа равноправных слов. Группа `болгарка, шлифмашина` добавила бы
«болгарку» в индекс к позиции «Шлифмашина» — и подсказка по мере набора начала бы предлагать
слово, которого в справочнике нет. Направление `болгарка => шлифмашина` разворачивает запрос
пользователя в слово справочника и не загрязняет сам справочник.

## Формы слова

Писать все падежи не нужно: фильтр стоит **до** стеммера, но правило `=>` сопоставляется с
исходным токеном. Поэтому частотные формы перечислены явно — «болгарка», «болгарки», — а
редкие («болгаркою») словарь не ловит, и это сознательный размен: лишние строки в словаре
стоят дороже, чем один непойманный падеж, который всё равно дойдёт до триграмм.
"""

