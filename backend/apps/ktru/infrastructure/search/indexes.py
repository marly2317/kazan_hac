"""Схема индексов OpenSearch: что умеет движок вместо нас.

Весь смысл переезда — здесь. Раньше поиск был выражением в SQL, которое мы считали сами:
сумма триграммных сходств по словам, относительный порог, ручное слияние оценок. Оно работало,
но за полноту отбора и за ранжирование отвечали мы, и совместить их в Postgres не удалось —
быстрые варианты теряли 36 процентных пунктов точности (замеры в `docs/SEARCH_CHOICE.md`).

Здесь за то же отвечает движок, и каждое поле названо тем, что оно решает:

| Поле | Чем занимается движок |
| --- | --- |
| `name` | русский стеммер и словарь синонимов — морфология и народные названия |
| `name.trigram` | опечатки и составные слова: «шлифмашина» против «шлифовальная машина» |
| `name.prefix` | набранное не до конца: «молот» находит «Молоток» |
| `head` | первое слово наименования — то, чем товар **является** |
| `vector` | kNN по HNSW: смысловая близость, когда общих букв нет вовсе |
| `values` (nested) | сужение по характеристикам: `terms` по текстам, `range` по диапазонам |

Слияние лексики и вектора тоже не наше: `hybrid` + `score-ranker-processor` с RRF (см.
:data:`PIPELINE`). RRF складывает **места**, а не оценки, и поэтому не требует их приводить к
одной шкале — а это ровно та задача, в которой самодельное слияние BM25 с косинусом и ошибается.

## Чего движку не передано, и почему

**Решение «не нашлось».** Любой поиск возвращает ближайшее, и уверенно неверный код хуже
честного отказа. Порог уверенности считается по словам наименования в
`apps.autofill.domain.matching` и остаётся нашим: он про предметную область, а не про поиск.
Оценка движка — RRF-число вроде 0.03 — для этого решения не годится в принципе, потому что это
место в списке, а не похожесть.

**Словарь синонимов.** Применяет его движок, но составляем его мы: см.
[`synonyms.py`](synonyms.py).
"""

from __future__ import annotations

from dataclasses import dataclass

from django.conf import settings

from apps.ktru.infrastructure.search.synonyms import SYNONYMS

#: Имя конвейера поиска, в котором живёт слияние лексики и вектора.
PIPELINE = "ktru-rrf"

#: Константа RRF: насколько быстро обесценивается место в списке.
#:
#: 60 — значение из исходной работы про RRF и общепринятое по умолчанию. Смысл: документ на
#: первом месте даёт 1/61, на десятом — 1/70, то есть разница между первым и десятым местом
#: меньше, чем между «нашёлся одним способом» и «нашёлся двумя». Это и нужно: позиция,
#: найденная и лексикой, и вектором, вероятнее той, которую нашёл только один из них.
RANK_CONSTANT = 60


def _analysis() -> dict:
    """Анализаторы: то, что превращает русский текст в сопоставимые токены.

    Четыре разных взгляда на одну строку, потому что ломаются они по-разному и порознь:
    стеммер не видит опечатку, триграммы не видят морфологию, префиксы нужны только при
    наборе. Движок умеет держать их в одном поле как подполя и искать по всем сразу.
    """
    return {
        "filter": {
            "ru_stop": {"type": "stop", "stopwords": "_russian_"},
            # Словарный стеммер, а не обрезка по пяти буквам. Именно он закрывает корзину
            # `morphology`: «шлифовальная» и «шлифовальный» — одна основа.
            "ru_stemmer": {"type": "stemmer", "language": "russian"},
            # `synonym_graph`, а не `synonym`: правило «углошлифовальная => шлифмашина»
            # заменяет один токен одним, но многословные правила граф разбирает верно, а
            # простой фильтр — нет. Стоит **до** стеммера: словарь написан в исходных формах.
            "ktru_synonyms": {"type": "synonym_graph", "synonyms": list(SYNONYMS)},
            "ru_trigram": {"type": "ngram", "min_gram": 3, "max_gram": 3},
            # 20 — предел осмысленного префикса: наименования длиннее, но набирать двадцать
            # символов, не закончив слово, уже некуда.
            "ru_edge": {"type": "edge_ngram", "min_gram": 2, "max_gram": 20},
        },
        "analyzer": {
            # Основной: регистр, стоп-слова, синонимы, основа.
            "ru_name": {
                "tokenizer": "standard",
                "filter": ["lowercase", "ru_stop", "ktru_synonyms", "ru_stemmer"],
            },
            # Он же без синонимов — для индексации. Разворачивать синонимы в индексе значило
            # бы положить в него слова, которых в справочнике нет, и подсказки начали бы их
            # предлагать. Направление «запрос → справочник», а не наоборот.
            "ru_name_index": {
                "tokenizer": "standard",
                "filter": ["lowercase", "ru_stop", "ru_stemmer"],
            },
            "ru_trigram": {"tokenizer": "standard", "filter": ["lowercase", "ru_trigram"]},
            # Префиксы кладутся в индекс, но **не** применяются к запросу: иначе «молоток»
            # искался бы как «мо», «мол», «моло»… и находил бы всё.
            "ru_prefix_index": {"tokenizer": "standard", "filter": ["lowercase", "ru_edge"]},
            "ru_prefix_search": {"tokenizer": "standard", "filter": ["lowercase"]},
            # Слово целиком, только в нижнем регистре: основа для `term`-подсказок об
            # опечатках. Стеммер здесь вреден — исправлять нужно к той форме, которую
            # пользователь увидит, а не к обрезанной основе.
            "ru_word": {"tokenizer": "keyword", "filter": ["lowercase"]},
        },
    }


def _value_properties() -> dict:
    """Одно допустимое значение одной характеристики одной позиции.

    Вложенная единица — **значение**, а не характеристика, и это выбор, от которого зависит,
    выразимо ли сужение запросом вообще. У характеристики значений много, у каждого свои
    единица измерения, границы и строгость границ; вложить значения внутрь вложенной
    характеристики движок позволяет, но запрос «есть ли у этой характеристики значение,
    допускающее 350 мм» стал бы вложенным в двух уровнях. Один документ на значение делает
    это одним условием.

    Цена — повтор имени характеристики в каждом значении. 43 815 значений на справочник
    категорий хакатона: несколько мегабайт, то есть ничто против читаемости запроса.
    """
    return {
        "characteristic_code": {"type": "keyword"},
        "characteristic": {
            "type": "text",
            "analyzer": "ru_name_index",
            "search_analyzer": "ru_name",
            "fields": {"raw": {"type": "keyword"}},
        },
        # Основы слов имени характеристики. Сужение сопоставляет имя, которое уже распознано
        # нашим кодом, поэтому сравнивать его нужно так же, как сравнивал он, — по основам, а
        # не через анализатор движка: иначе «Высота шкафа» и «высота» разойдутся на границе
        # между двумя разными представлениями об одной и той же основе.
        "stems": {"type": "keyword"},
        "required": {"type": "boolean"},
        # "1" качественная | "2" количественная — `apps.ktru.domain.enums.CharacteristicType`.
        "kind": {"type": "keyword"},
        # "text" | "exact" | "range" — `apps.ktru.domain.enums.ValueKind`.
        "value_kind": {"type": "keyword"},
        # Допустимый текст в нижнем регистре: сравнение значений — точное, а не нечёткое.
        # «Мужской» либо разрешён, либо нет; «похожий на разрешённый» здесь не бывает.
        "text": {"type": "keyword"},
        "unit": {"type": "keyword"},
        "exact": {"type": "double"},
        "minimum": {"type": "double"},
        "maximum": {"type": "double"},
        # Строгость границы — отдельным полем, потому что `greater` и `greaterOrEqual` в КТРУ
        # различаются, и спутать их значит принять значение, которое справочник отвергает.
        # В запросе это разворачивается в пару условий, см. `application/narrowing.py`.
        "min_inclusive": {"type": "boolean"},
        "max_inclusive": {"type": "boolean"},
    }


@dataclass(frozen=True)
class Index:
    """Индекс и его схема. Имя собирается с префиксом из настроек."""

    suffix: str

    @property
    def name(self) -> str:
        return f"{settings.OPENSEARCH_INDEX_PREFIX}_{self.suffix}"

    def named(self, prefix: str) -> str:
        """Имя с другим префиксом — для индекса под замер рядом с рабочим."""
        return f"{prefix}_{self.suffix}"


POSITIONS = Index("positions")
TERMS = Index("terms")


def positions_body(dimension: int) -> dict:
    """Схема индекса позиций. ``dimension`` берётся у энкодера, а не задаётся числом."""
    return {
        "settings": {
            "index": {
                "knn": True,
                # Один узел: реплику разместить негде, и запрос на неё оставил бы кластер
                # навсегда в состоянии `yellow` без всякой пользы.
                "number_of_shards": 1,
                "number_of_replicas": 0,
            },
            "analysis": _analysis(),
        },
        "mappings": {
            # Полей ровно столько, сколько описано: опечатка в имени поля при индексации
            # создала бы новое поле вместо ошибки, и расхождение нашлось бы на демонстрации.
            "dynamic": "strict",
            "properties": {
                "code": {"type": "keyword"},
                "name": {
                    "type": "text",
                    "analyzer": "ru_name_index",
                    "search_analyzer": "ru_name",
                    "fields": {
                        "raw": {"type": "keyword"},
                        "trigram": {"type": "text", "analyzer": "ru_trigram"},
                        "prefix": {
                            "type": "text",
                            "analyzer": "ru_prefix_index",
                            "search_analyzer": "ru_prefix_search",
                        },
                    },
                },
                # Первое слово наименования — то, чем товар является. Отдельным полем, потому
                # что «Бур для перфоратора» не отвечает на «перфоратор»: слово есть в
                # наименовании, но как указание на то, для чего товар, а не что он такое.
                "head": {
                    "type": "text",
                    "analyzer": "ru_name_index",
                    "search_analyzer": "ru_name",
                    "fields": {"raw": {"type": "keyword"}},
                },
                "okpd2_code": {"type": "keyword"},
                "okpd2_name": {"type": "text", "analyzer": "ru_name_index"},
                "vector": {
                    "type": "knn_vector",
                    "dimension": dimension,
                    "method": {
                        "name": "hnsw",
                        # Lucene, а не nmslib: движок держит граф в тех же файлах, что и
                        # остальной индекс, то есть снимок и восстановление работают сами.
                        "engine": "lucene",
                        # Косинус: длина вектора у энкодера не несёт смысла, а наименования
                        # позиций различаются по длине втрое.
                        "space_type": "cosinesimil",
                    },
                },
                # Имена характеристик позиции одной строкой. Нужно не для сужения, а для
                # отбора: описание «шкаф высота 2000» называет характеристику, и позиция, у
                # которой такая характеристика есть, вероятнее той, у которой её нет.
                "characteristic_names": {"type": "text", "analyzer": "ru_name_index"},
                "values": {"type": "nested", "properties": _value_properties()},
            },
        },
    }


def terms_body() -> dict:
    """Схема словаря справочника: подсказки по мере набора и исправление опечаток.

    Один индекс на две задачи, потому что словарь у них один и тот же — наименования позиций,
    имена характеристик, допустимые значения. Разные у них только инструменты движка:
    `completion` (конечный автомат) дополняет набираемое слово, `term`-подсказчик по полю
    `word` предлагает замену набранному с ошибкой.

    Документ — это **одно вхождение слова в одну фразу**, а не одно слово. Иначе не ответить
    на «какое слово идёт в справочнике после этого»: у слова предшественников много, и
    хранить их списком значило бы хранить то, что движок умеет отбирать сам полем `previous`.
    """
    return {
        "settings": {
            "index": {"number_of_shards": 1, "number_of_replicas": 0},
            "analysis": _analysis(),
        },
        "mappings": {
            "dynamic": "strict",
            "properties": {
                # Слово как есть — его и подставит интерфейс.
                "word": {
                    "type": "text",
                    "analyzer": "ru_word",
                    "fields": {"raw": {"type": "keyword"}},
                },
                # Конечный автомат для дополнения. `contexts` нет: фильтровать подсказки по
                # виду источника незачем — вид влияет на порядок, и порядок считается у нас
                # (`apps.autofill.domain.suggest.rank`), потому что он про предметную область.
                "suggest": {"type": "completion", "analyzer": "ru_word"},
                # Основа предыдущего слова фразы, либо пусто для первого. Так отвечается
                # «что идёт после»: `term`-фильтр вместо обхода словаря.
                "previous": {"type": "keyword"},
                # position | characteristic | value — `domain.suggest.SuggestionKind`.
                "kind": {"type": "keyword"},
                # Фраза, откуда слово взято: «зимняя» само по себе не говорит ничего,
                # «Куртка зимняя из кожи» говорит всё — и подтверждает, что позиция есть.
                "source": {"type": "keyword"},
                # Слово стоит первым в наименовании позиции, то есть называет сам товар.
                "is_head": {"type": "boolean"},
                "frequency": {"type": "integer"},
            },
        },
    }


def pipeline_body() -> dict:
    """Конвейер поиска, в котором происходит слияние лексики и вектора.

    `score-ranker-processor` с RRF складывает обратные **места** документа в каждом из
    подзапросов. Почему именно так, а не взвешенной суммой оценок: BM25 не ограничен сверху и
    зависит от длины запроса, косинус лежит в ``[0, 2]``. Привести их к одной шкале — отдельная
    задача с отдельными ошибками, и RRF её просто не ставит: места сравнимы всегда.
    """
    return {
        "description": "Слияние лексического и векторного поиска по позициям КТРУ (RRF)",
        "phase_results_processors": [
            {
                "score-ranker-processor": {
                    "combination": {"technique": "rrf", "rank_constant": RANK_CONSTANT}
                }
            }
        ],
    }
